namespace island {
// Small dark fish slivers under the pool's surface, rebuilt each frame from the field in one
// dynamic vertex-coloured draw, drawn before the stream water so the water tints them.
class StreamFishRenderer final {
public:
    static constexpr int VerticesPerFish=9;   // body (two triangles) and a tail fin
    explicit StreamFishRenderer(Microsoft::Xna::Framework::Graphics::GraphicsDevice& device);
    void Draw(const Microsoft::Xna::Framework::Matrix& view,
              const Microsoft::Xna::Framework::Matrix& projection,
              const Microsoft::Xna::Framework::Vector3& camera,
              std::span<const StreamFish> fish);
    [[nodiscard]] int DrawCallCount() const noexcept {return drawCalls_;}
    [[nodiscard]] int VisibleCount() const noexcept {return visible_;}
private:
    Microsoft::Xna::Framework::Graphics::GraphicsDevice& device_;
    std::unique_ptr<Microsoft::Xna::Framework::Graphics::BasicEffect> effect_;
    std::unique_ptr<Microsoft::Xna::Framework::Graphics::DynamicVertexBuffer> vertices_;
    std::vector<Microsoft::Xna::Framework::Graphics::VertexPositionColor> staging_;
    int drawCalls_=0,visible_=0;
};
}

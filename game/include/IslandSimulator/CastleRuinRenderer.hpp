#include <memory>

namespace island {
class IslandTerrain;
class RenderedTerrainSurface;
class SunShadowMap;

// The island's medieval castle ruin in one opaque vertex-coloured draw: a square curtain wall of
// coursed blocks, battlemented where it still stands, fallen ragged elsewhere, a round tower at
// each corner, the gate with half its arch gone, a stretch breached in the east wall, the roofless
// keep at the back with its windows and doorway, a gatehouse's two stumps, the courtyard's well
// and the rubble; moss, lichen and ivy on the stone; lit by the hour's sun and receiving and
// casting the sun shadows like the idol.
class CastleRuinRenderer final {
public:
    CastleRuinRenderer(Microsoft::Xna::Framework::Graphics::GraphicsDevice& device,
                       const CastleRuinPlacement& placement,const IslandTerrain& terrain,
                       const RenderedTerrainSurface& ground);
    void Draw(const Microsoft::Xna::Framework::Matrix& view,
              const Microsoft::Xna::Framework::Matrix& projection,
              const Microsoft::Xna::Framework::Vector3& camera);
    void DrawSunShadow(SunShadowMap& map);
    void SetSunShadowMap(const SunShadowMap* map) noexcept {sunShadow_=map;}
    [[nodiscard]] int DrawCallCount() const noexcept {return drawCalls_;}
    [[nodiscard]] int TriangleCount() const noexcept {return triangles_;}
private:
    Microsoft::Xna::Framework::Graphics::GraphicsDevice& device_;
    std::unique_ptr<Microsoft::Xna::Framework::Graphics::BasicEffect> effect_;
    std::unique_ptr<StructureShadowReceiver> receiver_;
    const SunShadowMap* sunShadow_=nullptr;
    std::unique_ptr<Microsoft::Xna::Framework::Graphics::ShaderEffect> sunShadowEffect_;
    std::unique_ptr<Microsoft::Xna::Framework::Graphics::VertexBuffer> vertices_;
    Microsoft::Xna::Framework::BoundingBox bounds_;
    Microsoft::Xna::Framework::Vector3 centre_;
    int triangles_=0,drawCalls_=0;
    bool sunShadowUnavailable_=false;
};
}
